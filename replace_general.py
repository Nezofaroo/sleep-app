def clean_styling_and_replace_text():
    print(f"Reading from {src_docx}...")
    with zipfile.ZipFile(src_docx, 'r') as docx_in:
        # We need to copy everything but modify word/document.xml
        xml_content = docx_in.read('word/document.xml')
        
        # Modify XML
        root = ET.fromstring(xml_content)
        paragraphs = root.findall('.//w:p', ns)
        print(f"Total paragraphs in source: {len(paragraphs)}")
        
        for idx, p in enumerate(paragraphs):
            # Gather text runs
            runs = p.findall('.//w:r', ns)
            
            # Clean Bold/Italic formatting from paragraph properties
            pPr = p.find('w:pPr', ns)
            if pPr is not None:
                # Remove bold/italic tags
                for tag in ['w:b', 'w:bCs', 'w:i', 'w:iCs']:
                    elem = pPr.find(tag, ns)
                    if elem is not None:
                        pPr.remove(elem)
            
            # 1. Text replacement
            if idx in REPLACEMENTS:
                new_text = REPLACEMENTS[idx]
                # Put new_text in the first run's text node, clear others
                txt_set = False
                for r in runs:
                    t = r.find('w:t', ns)
                    if t is not None:
                        if not txt_set:
                            t.text = new_text
                            txt_set = True
                        else:
                            t.text = ""
                # If no runs or text elements found, let's inject one
                if not txt_set:
                    # Create w:r and w:t
                    r_new = ET.Element('{http://schemas.openxmlformats.org/wordprocessingml/2006/main}r')
                    t_new = ET.Element('{http://schemas.openxmlformats.org/wordprocessingml/2006/main}t')
                    t_new.text = new_text
                    r_new.append(t_new)
                    p.append(r_new)
                    runs = [r_new]
            
            # 2. Styling removal for runs (strip bold and italic)
            for r in runs:
                # Clean Bold/Italic formatting from run properties
                rPr = r.find('w:rPr', ns)
                if rPr is not None:
                    for tag in ['w:b', 'w:bCs', 'w:i', 'w:iCs']:
                        elem = rPr.find(tag, ns)
                        if elem is not None:
                            rPr.remove(elem)
                            
            # 3. Apply string replacements to catch any leaks of old terminology in unmodified paragraphs
            for r in runs:
                t = r.find('w:t', ns)
                if t is not None and t.text:
                    orig = t.text
                    replaced = orig
                    replaced = replaced.replace("Linguaphile", "Sleep.ly")
                    replaced = replaced.replace("Linguaphile-дің", "Sleep.ly-дің")
                    replaced = replaced.replace("Linguaphile-де", "Sleep.ly-де")
                    replaced = replaced.replace("Kotlin", "Dart")
                    replaced = replaced.replace("Android SDK", "Flutter SDK")
                    replaced = replaced.replace("SharedPreferences", "Hive")
                    replaced = replaced.replace("Intent", "Navigator")
                    replaced = replaced.replace("Firebase Firestore", "SQLite (Sqflite)")
                    replaced = replaced.replace("Firebase Authentication", "Жергілікті сақтау")
                    replaced = replaced.replace("LiveData", "Streams")
                    replaced = replaced.replace("ViewModel", "Provider")
                    replaced = replaced.replace("Repository", "DatabaseHelper")
                    replaced = replaced.replace("Activity", "Widget")
                    replaced = replaced.replace("Fragment", "Screen")
                    if replaced != orig:
                        t.text = replaced
        
        # Save modified XML back
        modified_xml = ET.tostring(root, encoding='utf-8')
        
        # Write modified zip back
        print(f"Writing to {dest_docx}...")
        with zipfile.ZipFile(dest_docx, 'w', zipfile.ZIP_DEFLATED) as docx_out:
            for item in docx_in.infolist():
                if item.filename == 'word/document.xml':
                    docx_out.writestr(item, modified_xml)
                else:
                    docx_out.writestr(item, docx_in.read(item.filename))
                    
    print("Document successfully created!")

if __name__ == "__main__":
    clean_styling_and_replace_text()
